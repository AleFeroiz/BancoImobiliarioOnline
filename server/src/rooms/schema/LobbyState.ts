import { schema, t, type SchemaType } from '@colyseus/schema'
import { DEFAULT_ANIMATION_SPEED } from '../../../../shared/game.js'

export const LobbyPlayerState = schema({
  name: t.string().default(''),
  isHost: t.boolean().default(false),
  isReady: t.boolean().default(false),
  isConnected: t.boolean().default(true),
  reconnectionExpired: t.boolean().default(false),
  isBot: t.boolean().default(false),
  isBotControlled: t.boolean().default(false),
  isInactive: t.boolean().default(false),
  controllerSessionId: t.string().default(''),
  characterType: t.string().default('pawn'),
  color: t.string().default('#ce7558'),
  position: t.uint8().default(0),
  hasCompletedFirstLap: t.boolean().default(false),
  cash: t.int32().default(0),
  loanCount: t.uint16().default(0),
  loanAmount: t.int32().default(0),
  loanDue: t.int32().default(0),
  loanUsedThisLap: t.boolean().default(false),
  betUsedThisLap: t.boolean().default(false),
  betLapRevision: t.uint32().default(0),
  nextRentMultiplier: t.float32().default(1),
  devInfiniteCash: t.boolean().default(false),
  isJailed: t.boolean().default(false),
  jailTurns: t.uint8().default(0),
  isBankrupt: t.boolean().default(false),
  finalCash: t.int32().default(0),
  finalNetWorth: t.int32().default(0),
  tieBreakRoll: t.uint8().default(0),
})

export type LobbyPlayerState = SchemaType<typeof LobbyPlayerState>

export const PropertyState = schema({
  ownerSessionId: t.string().default(''),
  houses: t.uint8().default(0),
  blackoutTurns: t.uint8().default(0),
  protectionTurns: t.uint8().default(0),
})

export type PropertyState = SchemaType<typeof PropertyState>

export const LobbyState = schema({
  players: t.map(LobbyPlayerState),
  properties: t.map(PropertyState),
  roomCode: t.string().default(''),
  mode: t.string().default('classic'),
  matchDuration: t.uint16().default(1800),
  cupInitialMultiplier: t.float32().default(2),
  festivalMultiplier: t.float32().default(2),
  festivalCount: t.uint8().default(3),
  startingCash: t.uint32().default(2000000),
  jailTurnLimit: t.uint8().default(3),
  decisionSeconds: t.uint16().default(15),
  turnOrder: t.string().default(''),
  animationSpeed: t.float32().default(DEFAULT_ANIMATION_SPEED),
  devToolsEnabled: t.boolean().default(false),
  presentationSpeed: t.float32().default(DEFAULT_ANIMATION_SPEED),
  status: t.string().default('waiting'),
  turnPhase: t.string().default('roll'),
  activePlayerSessionId: t.string().default(''),
  turnNumber: t.uint16().default(0),
  turnSeconds: t.uint8().default(0),
  matchSeconds: t.uint16().default(0),
  matchEnding: t.boolean().default(false),
  diceOne: t.uint8().default(0),
  diceTwo: t.uint8().default(0),
  diceSequence: t.uint32().default(0),
  pawnMoveMode: t.string().default('walk'),
  landingDescription: t.string().default(''),
  activeCardTitle: t.string().default(''),
  activeCardDescription: t.string().default(''),
  activeCardId: t.string().default(''),
  activeCardUserName: t.string().default(''),
  pendingPropertyId: t.uint8().default(255),
  festivalSpaceIds: t.string().default(''),
  worldCupSpaceId: t.uint8().default(255),
  worldCupHostCount: t.uint16().default(0),
  debtAmount: t.int32().default(0),
  debtCreditorSessionId: t.string().default(''),
  debtReason: t.string().default(''),
  winnerSessionId: t.string().default(''),
  matchEndReason: t.string().default(''),
  auctionId: t.uint32().default(0),
  auctionPropertyId: t.uint8().default(255),
  auctionSellerSessionId: t.string().default(''),
  auctionStartingBid: t.int32().default(0),
  auctionHighestBid: t.int32().default(0),
  auctionHighestBidderSessionId: t.string().default(''),
  auctionPhase: t.string().default(''),
  auctionSeconds: t.uint8().default(0),
  auctionCooldownSeconds: t.uint16().default(0),
  auctionRequestId: t.uint32().default(0),
  auctionRequestPropertyId: t.uint8().default(255),
  auctionRequestSellerSessionId: t.string().default(''),
  auctionRequestorSessionId: t.string().default(''),
  auctionRequestBid: t.int32().default(0),
  auctionRequestSeconds: t.uint8().default(0),
  auctionPausedTurnPhase: t.string().default(''),
  auctionPausedTurnSeconds: t.uint8().default(0),
  auctionOrigin: t.string().default(''),
})

export type LobbyState = SchemaType<typeof LobbyState>
